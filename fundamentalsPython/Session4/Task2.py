# grade calculation

marks = int(input("enter your marks (0 - 100) :"))

if marks >= 90:
    print("Grade : A")
elif marks >=75:
    print("Grade : B")
elif marks >=60:
    print("Grade : C")
elif marks >= 40:
    print("Grade : D")
else:
    print("Fail : F")

